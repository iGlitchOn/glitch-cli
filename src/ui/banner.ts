export const GLITCH_ASCII_ART = GLITCH_ASCII_LINES.join(os.EOL);

export function formatShortCwd(cwd: string = process.cwd()): string {
  const home = os.homedir();
  const normalizedHome = path.resolve(home);
  const normalizedCwd = path.resolve(cwd);

  if (normalizedCwd.toLowerCase() === normalizedHome.toLowerCase()) {
    return '~';
  }
  if (
    normalizedCwd.toLowerCase().startsWith(normalizedHome.toLowerCase() + path.sep)
  ) {
    return '~' + normalizedCwd.slice(normalizedHome.length);
  }
  return normalizedCwd;
}

/**
 * Renderiza la pantalla inicial al estilo OpenAI Codex CLI:
 * - Cabecera superior izquierda: `>_ Glitch CLI (v0.1.0)` y directorio actual (`~`).
 * - Arte ASCII centrado en la ventana de terminal.
 * - Leyenda inferior de ayuda rápida (`? para atajos`).
 */
export function formatStartupBanner(
  version = '0.1.0',
  terminalColumns = process.stdout.columns || 100,
  cwd: string = process.cwd(),
): string {
  const artWidth = GLITCH_ASCII_LINES[0]?.length ?? 80;
  const leftPadCount = Math.max(0, Math.floor((terminalColumns - artWidth) / 2));
  const pad = ' '.repeat(leftPadCount);

  const dim = '\x1b[90m';
  const boldWhite = '\x1b[1;97m';
  const reset = '\x1b[0m';

  const headerLine1 = `  ${boldWhite}>_ Glitch CLI${reset} ${dim}(v${version})${reset}`;
  const headerLine2 = `     ${dim}${formatShortCwd(cwd)}${reset}`;

  const centeredArt = GLITCH_ASCII_LINES.map(
    (line) => `${pad}${dim}${line}${reset}`,
  ).join(os.EOL);

  const footerHint = `  ${dim}? escribe /help para comandos o Shift+Tab para alternar Plan/Agent${reset}`;

  return [
    '',
    headerLine1,
    headerLine2,
    '',
    centeredArt,
    '',
    footerHint,
    '',
  ].join(os.EOL);
}
